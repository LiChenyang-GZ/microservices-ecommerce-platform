/**
 * 失败场景表 B11（🟠，Christy 选了 ❓3 的 a：启动时幂等 SQL）、D9（delivery 那份）。
 * 和 store 的 FreshEnvironmentIntegrationTest 一样：自己起一套 Postgres + Kafka，在 Spring 启动**之前**摆好环境。
 *
 *   1. B11：先建一张和 Christy 现在 delivery_db 一模一样的旧 delivery 表（2026-10-20 用 \d delivery 查过）：
 *      user_name、email 等是 NOT NULL，order_id **没有**唯一约束。ddl-auto=update 不会去掉 NOT NULL，
 *      也不保证加上唯一约束（已有重复数据时 ALTER 失败只打一行日志）→ 取消标记插不进去、去重悄悄失效。
 *   2. D9：Spring 启动前先往 order-events 发一条 OrderPaid。delivery 的消费者组第一次出现，
 *      要从最早读（auto-offset-reset=earliest），否则这单永远不会有配送单。
 *
 * 【层】集成测试。不继承 DeliveryIntegrationTest（那套容器是全新的空库）。
 */
@SpringBootTest(properties = {
        "DELIVERY_DB_PASSWORD=unused-overridden-by-testcontainers",
        "RABBITMQ_USERNAME=guest",
        "RABBITMQ_PASSWORD=guest",
        "spring.rabbitmq.port=1",
        "spring.rabbitmq.listener.simple.auto-startup=false",
        "event-outbox.publisher.interval-ms=200"
})
class DeliveryFreshEnvironmentIntegrationTest {

    private static final String EARLY_ORDER_ID = "424242";

    @ServiceConnection
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");

    static final KafkaContainer KAFKA = new KafkaContainer("apache/kafka:3.9.1")
            .withEnv("KAFKA_AUTO_CREATE_TOPICS_ENABLE", "false");

    static {
        POSTGRES.start();
        KAFKA.start();
        KafkaProbe kafka = new KafkaProbe(KAFKA.getBootstrapServers());
        kafka.createTopics(KafkaProbe.ALL_TOPICS);
        createOldDeliveryTable();
        kafka.send(Topics.ORDER_EVENTS, EARLY_ORDER_ID, EventCodec.write(orderPaid(EARLY_ORDER_ID)));
    }

    /** 和 Christy 库里一样的旧表（列、NOT NULL、CHECK），没有 order_id 唯一约束 */
    private static void createOldDeliveryTable() {
        try (Connection c = DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
             Statement st = c.createStatement()) {
            st.execute("""
                    CREATE TABLE delivery (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        creation_time timestamp(6) NOT NULL,
                        delivery_status varchar(255) NOT NULL,
                        email varchar(255) NOT NULL,
                        from_address varchar(255) NOT NULL,
                        notification_url varchar(255),
                        order_id varchar(255),
                        product_name varchar(255) NOT NULL,
                        quantity integer NOT NULL,
                        retry_count integer NOT NULL,
                        to_address varchar(255) NOT NULL,
                        update_time timestamp(6) NOT NULL,
                        user_name varchar(255) NOT NULL,
                        version integer NOT NULL,
                        CONSTRAINT delivery_delivery_status_check CHECK (delivery_status IN
                            ('CREATED', 'PICKED_UP', 'DELIVERING', 'RECEIVED', 'LOST', 'CANCELLED'))
                    )""");
        } catch (Exception e) {
            throw new IllegalStateException("cannot create the old delivery table", e);
        }
    }

    @DynamicPropertySource
    static void kafkaAddress(DynamicPropertyRegistry registry) {
        registry.add("spring.kafka.bootstrap-servers", KAFKA::getBootstrapServers);
    }

    @MockitoBean
    RabbitTemplate rabbitTemplate;

    @Autowired
    JdbcTemplate jdbc;

    /** B11：启动后 order_id 有唯一约束（或唯一索引），取消标记不需要的列可以为空 */
    @Test
    void existingDeliveryTable_getsUniqueOrderId_andNullableColumns() {
        Integer uniqueOnOrderId = jdbc.queryForObject("""
                SELECT count(*) FROM pg_index i
                JOIN pg_class t ON t.oid = i.indrelid
                JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY (i.indkey)
                WHERE t.relname = 'delivery' AND i.indisunique AND a.attname = 'order_id' AND i.indnatts = 1
                """, Integer.class);
        assertThat(uniqueOnOrderId).as("order_id 上的唯一索引").isGreaterThanOrEqualTo(1);

        for (String column : new String[]{"email", "user_name", "to_address", "from_address", "product_name"}) {
            String nullable = jdbc.queryForObject("""
                    SELECT is_nullable FROM information_schema.columns
                    WHERE table_name = 'delivery' AND column_name = ?""", String.class, column);
            assertThat(nullable).as("%s 要允许为空（取消标记没有这些值）", column).isEqualTo("YES");
        }
    }

    /** D9：启动前就在 topic 里的 OrderPaid 也被读到、建了单 */
    @Test
    void newConsumerGroup_readsOrderPaidPublishedBeforeItStarted() {
        await().atMost(Duration.ofSeconds(20)).until(() -> jdbc.queryForObject(
                "SELECT count(*) FROM delivery WHERE order_id = ?", Integer.class, EARLY_ORDER_ID) == 1);
    }

    /** 和 DeliveryIntegrationTest.orderPaid 一样的 OrderPaid（这里不引用那个类：它的 static 块会多起一套容器） */
    private static EventEnvelope orderPaid(String orderId) {
        return new EventEnvelope(UUID.randomUUID(), OrderEventType.ORDER_PAID.wireName(), orderId, Instant.now(),
                EventCodec.toTree(new OrderPaidPayload(Long.parseLong(orderId), new BigDecimal("6999.00"), "9001",
                        "early@test.local", "early", "1 Test Street", List.of("Warehouse-1"), "Test Phone", 1)));
    }
}

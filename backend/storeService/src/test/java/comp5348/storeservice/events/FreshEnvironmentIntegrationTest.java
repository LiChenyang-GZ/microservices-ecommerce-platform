/**
 * 失败场景表 A15、D9：两件只有在"不是全新环境"或"服务比事件晚启动"时才会出事的情况。
 * 普通的集成测试测不出来：它们每次都用全新的空库，而且 store 总是比测试发的事件先启动。
 *
 * 所以这个类不继承 StoreIntegrationTest，自己起一套 Postgres + Kafka，并在 Spring 启动**之前**把环境摆好：
 *   1. A15：Postgres 里先建一张"旧的" orders 表，带着 Hibernate 当初生成的 CHECK 约束（只认旧的 10 个状态）。
 *      这正是 Christy 现在 compose 库里的样子（2026-10-20 查过 orders_status_check）。
 *      Spring 启动时 ddl-auto=update 只会补列，不会改这个约束。
 *   2. D9：Spring 启动前，先往 delivery-events 发一条事件（指向一个不存在的订单，所以它最终该进 DLT）。
 *      store 的消费者组是第一次出现，Kafka 默认从"最新"开始读，会把这条跳过。
 *
 * 【层】集成测试。启动一套新容器，比别的测试类慢十几秒。
 */
@SpringBootTest(properties = {
        "jwt.secret=test-only-secret-test-only-secret-0123456789abcdef",
        "RABBITMQ_USERNAME=guest",
        "RABBITMQ_PASSWORD=guest",
        "spring.rabbitmq.port=1",
        "outbox.processor.enabled=true"
})
@Import(TestInfraConfig.class)
class FreshEnvironmentIntegrationTest {

    /** 启动前就已经在 topic 里的那条事件指向的订单号（store 里没有这一单） */
    private static final String EARLY_ORDER_ID = "424242424242";

    @ServiceConnection
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16-alpine");

    static final KafkaContainer KAFKA = new KafkaContainer("apache/kafka:3.9.1")
            .withEnv("KAFKA_AUTO_CREATE_TOPICS_ENABLE", "false");

    static final KafkaProbe kafka;

    static {
        POSTGRES.start();
        KAFKA.start();
        kafka = new KafkaProbe(KAFKA.getBootstrapServers());
        kafka.createTopics(KafkaProbe.ALL_TOPICS);
        createOldOrdersTable();
        // 一条早于 store 启动的事件（格式完全正确，只是订单不存在 → 规则 6：进 DLT）
        kafka.send(Topics.DELIVERY_EVENTS, EARLY_ORDER_ID, """
                {"eventId":"0b6c3a52-2f0e-4c3a-9f7e-0000000000d9","eventType":"PickedUp","orderId":"%s",
                 "occurredAt":"2026-10-20T00:00:00Z","payload":{"deliveryId":1,"status":"PICKED_UP"}}
                """.formatted(EARLY_ORDER_ID));
    }

    /** 和 Christy 库里一样的旧约束：Hibernate 6 给 @Enumerated(STRING) 列生成的 CHECK，只有当时的枚举值 */
    private static void createOldOrdersTable() {
        try (Connection c = DriverManager.getConnection(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
             Statement st = c.createStatement()) {
            st.execute("""
                    CREATE TABLE orders (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        status varchar(255) NOT NULL,
                        CONSTRAINT orders_status_check CHECK (status IN ('PENDING_STOCK_HOLD', 'PLACED',
                            'PENDING_PAYMENT', 'PAID', 'PROCESSING', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED',
                            'CANCELLED', 'CANCELLED_SYSTEM'))
                    )""");
        } catch (Exception e) {
            throw new IllegalStateException("cannot create the old orders table", e);
        }
    }

    @DynamicPropertySource
    static void kafkaAddress(DynamicPropertyRegistry registry) {
        registry.add("spring.kafka.bootstrap-servers", KAFKA::getBootstrapServers);
    }

    @MockitoBean
    EmailAdapter emailAdapter;

    @Autowired
    JdbcTemplate jdbc;

    /**
     * A15（🟠，Christy 选了 ❓3 的 a：启动时跑幂等 SQL）：升级后的 store 在旧库上启动，
     * orders.status 上的 CHECK 约束必须接受 LOST 和 REFUNDED（或者干脆不再有 CHECK）。
     * 红灯：约束还是旧的，里面没有 LOST。
     */
    @Test
    void existingOrdersTable_withOldCheck_acceptsLostAndRefunded() {
        List<String> checks = jdbc.queryForList("""
                SELECT pg_get_constraintdef(c.oid)
                FROM pg_constraint c JOIN pg_class t ON c.conrelid = t.oid
                WHERE t.relname = 'orders' AND c.contype = 'c'
                """, String.class);
        assertThat(checks).filteredOn(def -> def.contains("status"))
                .allSatisfy(def -> assertThat(def).contains("'LOST'").contains("'REFUNDED'"));
    }

    /**
     * D9：store 的消费者组第一次启动时，topic 里已经有的事件也要读（auto-offset-reset=earliest）。
     * 看得见的结果：启动前那条事件被读到了，因为订单不存在而进了 DLT。如果被跳过，DLT 里永远不会有它。
     */
    @Test
    void newConsumerGroup_readsEventsPublishedBeforeItStarted() {
        kafka.awaitRecord(Topics.deadLetter(Topics.DELIVERY_EVENTS), r -> EARLY_ORDER_ID.equals(r.key()),
                Duration.ofSeconds(20));
    }
}
